function showAddFriend() {
  openModal(`<span class="modal-kicker">${icon("users")} ${t("friendsTitle")}</span><h2 class="modal-title">${t("addFriendsTitle")}</h2><p class="modal-copy">${t("addFriendsCopy")}</p><form class="form-stack" id="friend-form"><label class="form-field">${t("friendHandle")}<input name="handle" required maxlength="32" autocomplete="off" placeholder="@username"/></label><div class="profile-search-results" id="profile-search-results"></div><span class="form-error hidden" id="friend-form-error" role="alert"></span><button class="button button-dark" type="submit">${icon("plus")}${t("saveFriend")}</button></form>${window.wallBackend?.configured ? "" : `<p class="friends-demo-note modal-friends-note">${t("authConfigMissing")}</p>`}`);
  const form = document.getElementById("friend-form");
  const handleInput = form.elements.namedItem("handle");
  let profiles = [];
  handleInput.addEventListener("input", async () => {
    if (!window.wallBackend?.configured || !currentUser || handleInput.value.trim().length < 2) return;
    try {
      profiles = await window.wallBackend.searchProfiles(handleInput.value.trim());
      const results = profiles.filter((profile) => profile.id !== currentUser.id);
      document.getElementById("profile-search-results").innerHTML = results.map((profile) => `<button class="profile-search-result" type="button" data-profile-id="${escapeHtml(profile.id)}" data-profile-handle="${escapeHtml(profile.handle)}">${avatarMarkup(profile.display_name, "friend-avatar", profile.avatar_url)}<span><strong>${escapeHtml(profile.display_name)}</strong><small>@${escapeHtml(profile.handle)}</small></span>${icon("plus")}</button>`).join("");
    } catch (error) {
      showDataError(error);
    }
  });
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const handle = String(new FormData(form).get("handle")).trim().replace(/^@+/, "").toLowerCase();
    if (!handle) return;
    try {
      if (window.wallBackend?.configured) {
        if (!currentUser) {
          closeModal();
          showLogin();
          return;
        }
        await window.wallBackend.addFriendByHandle(handle);
        followedIds = new Set(await window.wallBackend.getFollowedIds());
        friends = await window.wallBackend.getFollowingProfiles();
      } else {
        const localHandle = `@${handle}`;
        if (friends.some((friend) => friend.handle.toLowerCase() === localHandle)) return showToast(t("duplicateFriend"));
        friends.unshift({ id: `friend-${Date.now()}`, name: localHandle.slice(1), handle: localHandle });
        saveFriends();
      }
      activeView = "friends";
      renderNav();
      updateViewTitle();
      closeModal();
      showToast(t("friendAdded"));
    } catch (error) {
      document.getElementById("friend-form-error").textContent = error.code === "PGRST116" ? t("profileNotFound") : error.message;
      document.getElementById("friend-form-error").classList.remove("hidden");
    }
  });
  document.getElementById("profile-search-results").addEventListener("click", (event) => {
    const result = event.target.closest("[data-profile-handle]");
    if (result) handleInput.value = result.dataset.profileHandle;
  });
}

