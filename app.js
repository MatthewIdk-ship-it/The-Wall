function installComposer() {
  const form = document.getElementById("feed-composer-form");
  const textarea = document.getElementById("composer-prompt");
  const imageInput = document.getElementById("image-input");
  imageInput.addEventListener("change", () => {
    const file = imageInput.files?.[0];
    if (!file) return;
    if (!["image/jpeg", "image/png", "image/webp", "image/gif"].includes(file.type)) {
      imageInput.value = "";
      return showToast(t("imageOnly"));
    }
    if (file.size > 10 * 1024 * 1024) {
      imageInput.value = "";
      return showToast(t("imageTooLarge"));
    }
    selectedImage = file;
    if (imagePreviewUrl) URL.revokeObjectURL(imagePreviewUrl);
    imagePreviewUrl = URL.createObjectURL(file);
    document.getElementById("upload-preview").innerHTML = `<img src="${imagePreviewUrl}" alt="${escapeHtml(file.name)}"/><button type="button" class="remove-upload" id="remove-upload" aria-label="${t("removeImage")}">${icon("close")}</button>`;
    document.getElementById("upload-preview").classList.remove("hidden");
  });
  form.addEventListener("click", (event) => {
    if (!event.target.closest("#remove-upload")) return;
    selectedImage = null;
    imageInput.value = "";
    if (imagePreviewUrl) URL.revokeObjectURL(imagePreviewUrl);
    imagePreviewUrl = null;
    document.getElementById("upload-preview").classList.add("hidden");
    document.getElementById("upload-preview").innerHTML = "";
  });
  textarea.addEventListener("keydown", (event) => {
    if (event.key === "Enter" && !event.shiftKey && !event.isComposing) {
      event.preventDefault();
      form.requestSubmit();
    }
  });
  textarea.addEventListener("input", () => {
    resizeTextarea(textarea);
    void updateMentionSuggestions(textarea);
  });
  resizeTextarea(textarea);
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const body = String(new FormData(form).get("body")).trim();
    if (!body && !selectedImage) return showToast(t("emptyPost"));
    if (!window.wallBackend?.configured) return showToast(t("authConfigMissing"));
    if (!currentUser) {
      showLogin();
      return;
    }
    const submit = form.querySelector('[type="submit"]');
    submit.disabled = true;
    try {
      await window.wallBackend.publishPost({ body, image: selectedImage });
      form.reset();
      selectedImage = null;
      if (imagePreviewUrl) URL.revokeObjectURL(imagePreviewUrl);
      imagePreviewUrl = null;
      document.getElementById("upload-preview").classList.add("hidden");
      document.getElementById("upload-preview").innerHTML = "";
      await refreshBackendData();
      showToast(t("posted"));
    } catch (error) {
      showDataError(error);
    } finally {
      submit.disabled = false;
    }
  });
}

function resizeTextarea(textarea) {
  textarea.style.height = "auto";
  const maxHeight = Number.parseFloat(getComputedStyle(textarea).maxHeight) || Infinity;
  textarea.style.height = `${Math.min(textarea.scrollHeight, maxHeight)}px`;
  textarea.style.overflowY = textarea.scrollHeight > maxHeight ? "auto" : "hidden";
}

async function updateMentionSuggestions(textarea) {
  if (!window.wallBackend?.configured || !currentUser) return;
  const cursor = textarea.selectionStart;
  const beforeCursor = textarea.value.slice(0, cursor);
  const match = beforeCursor.match(/(?:^|\s)@([a-zA-Z0-9._-]{1,32})$/);
  const popover = document.getElementById("mention-suggestions");
  if (!match || match[1].length < 2) {
    popover?.remove();
    return;
  }
  const token = match[1];
  const request = ++mentionRequest;
  try {
    const profiles = await window.wallBackend.searchProfiles(token);
    if (request !== mentionRequest || textarea !== document.activeElement) return;
    let menu = document.getElementById("mention-suggestions");
    if (!menu) {
      menu = document.createElement("div");
      menu.id = "mention-suggestions";
      menu.className = "mention-suggestions";
      textarea.closest(".composer-top").append(menu);
    }
    const matches = profiles.filter((profile) => profile.id !== currentUser.id);
    menu.innerHTML = matches.map((profile) => `<button type="button" data-mention="${escapeHtml(profile.handle)}"><strong>${escapeHtml(profile.display_name)}</strong><small>@${escapeHtml(profile.handle)}</small></button>`).join("");
  } catch (error) {
    console.warn("Mention suggestions could not be loaded.", error);
  }
}

document.addEventListener("click", (event) => {
  const mention = event.target.closest("[data-mention]");
  if (!mention) return;
  const textarea = document.getElementById("composer-prompt");
  const cursor = textarea.selectionStart;
  const before = textarea.value.slice(0, cursor).replace(/(?:^|\s)@([a-zA-Z0-9._-]{1,32})$/, (match) => match.startsWith(" ") ? " " : "");
  const after = textarea.value.slice(cursor);
  const insertion = `@${mention.dataset.mention} `;
  textarea.value = `${before}${insertion}${after}`;
  textarea.focus();
  const next = before.length + insertion.length;
  textarea.setSelectionRange(next, next);
  document.getElementById("mention-suggestions")?.remove();
});

document.addEventListener("click", async (event) => {
  const trendTag = event.target.closest("[data-trend-tag], .post-tag");
  if (trendTag) {
    event.preventDefault();
    document.getElementById("search-input").value = trendTag.dataset.trendTag || trendTag.textContent;
    activeView = "explore";
    renderNav();
    updateViewTitle();
    return;
  }
  const storyIndexButton = event.target.closest("[data-story-index]");
  if (storyIndexButton) {
    currentStoryIndex = Number(storyIndexButton.dataset.storyIndex);
    renderStoryViewer();
    return;
  }
  if (event.target.closest("[data-story-previous]") && currentStoryIndex > 0) {
    currentStoryIndex -= 1;
    renderStoryViewer();
    return;
  }
  if (event.target.closest("[data-story-next]") && currentStoryIndex < stories.length - 1) {
    currentStoryIndex += 1;
    renderStoryViewer();
    return;
  }
  if (event.target.closest("#see-all-stories")) {
    showStoryList();
    return;
  }
  if (event.target.closest("#show-all-trends")) {
    showAllTrends = !showAllTrends;
    renderTrends();
    return;
  }
  const viewButton = event.target.closest("[data-view]");
  if (viewButton) {
    activeView = viewButton.dataset.view;
    renderNav();
    updateViewTitle();
    return;
  }
  const removeFriendButton = event.target.closest("[data-remove-friend]");
  if (removeFriendButton) {
    friends = friends.filter((friend) => friend.id !== removeFriendButton.dataset.removeFriend);
    saveFriends();
    renderFriends();
    showToast(t("friendRemoved"));
    return;
  }
  const unfollowButton = event.target.closest("[data-unfollow]");
  if (unfollowButton) {
    try {
      await window.wallBackend.toggleFollow(unfollowButton.dataset.unfollow, false);
      followedIds.delete(unfollowButton.dataset.unfollow);
      friends = friends.filter((friend) => friend.id !== unfollowButton.dataset.unfollow);
      renderFriends();
      showToast(t("friendRemoved"));
    } catch (error) {
      showDataError(error);
    }
    return;
  }
  const notificationButton = event.target.closest("[data-notification-post]");
  if (notificationButton) {
    activeView = "home";
    renderNav();
    updateViewTitle();
    const postId = notificationButton.dataset.notificationPost;
    if (postId) document.querySelector(`[data-post-id="${CSS.escape(postId)}"]`)?.scrollIntoView({ behavior: "smooth", block: "center" });
    return;
  }
  const actionButton = event.target.closest("[data-action]");
  if (actionButton) {
    const card = actionButton.closest("[data-post-id]");
    const post = posts.find((entry) => entry.id === card?.dataset.postId);
    if (!post) return;
    const action = actionButton.dataset.action;
    if (action === "like") {
      const liked = currentPostState.liked.has(post.id) || post.liked;
      try {
        if (post.remote) await window.wallBackend.toggleLike(post.id, !liked);
        else {
          post.liked = !liked;
          post.likes += liked ? -1 : 1;
          savePosts();
        }
        if (liked) currentPostState.liked.delete(post.id);
        else currentPostState.liked.add(post.id);
        await refreshBackendData();
        if (!liked) showToast(t("likedToast"));
      } catch (error) {
        if (!currentUser) showLogin();
        else showDataError(error);
      }
    }
    if (action === "save") {
      const saved = currentPostState.saved.has(post.id) || post.saved;
      try {
        if (post.remote) await window.wallBackend.toggleSave(post.id, !saved);
        else {
          post.saved = !saved;
          savePosts();
        }
        if (saved) currentPostState.saved.delete(post.id);
        else currentPostState.saved.add(post.id);
        renderPosts();
        showToast(t(saved ? "removedSaved" : "saved"));
      } catch (error) {
        if (!currentUser) showLogin();
        else showDataError(error);
      }
    }
    if (action === "share") {
      const url = `${window.location.origin}${window.location.pathname}#${encodeURIComponent(post.id)}`;
      try {
        await navigator.clipboard.writeText(url);
        showToast(t("copied"));
      } catch {
        showToast(url);
      }
    }
    if (action === "comment") card.querySelector(".post-comment textarea")?.focus();
    if (action === "follow") {
      const following = followedIds.has(post.authorId);
      try {
        await window.wallBackend.toggleFollow(post.authorId, !following);
        if (following) followedIds.delete(post.authorId);
        else followedIds.add(post.authorId);
        friends = await window.wallBackend.getFollowingProfiles();
        renderPosts();
        showToast(t(following ? "unfollowed" : "subscribed"));
      } catch (error) {
        if (!currentUser) showLogin();
        else showDataError(error);
      }
    }
    return;
  }
  if (event.target.closest("#open-settings") || event.target.closest("#open-settings-bottom") || event.target.closest("#open-settings-mobile")) showSettings();
  if (event.target.closest("#open-login")) {
    if (currentUser) {
      try {
        await window.wallBackend.signOut();
      } catch (error) {
        showDataError(error);
      }
    } else showLogin(false);
  }
  if (event.target.closest("#desktop-compose") || event.target.closest("#mobile-compose")) focusComposer();
  if (event.target.closest("#language-button")) showLanguages();
  if (event.target.closest("[data-open-languages]")) showLanguages();
  if (event.target.closest("[data-open-friends]")) showAddFriend();
  if (event.target.closest("#theme-quick")) {
    state.theme = state.theme === "dark" ? "light" : "dark";
    saveState();
    applyTheme();
    showToast(t("themeChanged"));
  }
  if (event.target.closest("#profile-switch") || event.target.closest("#mobile-profile")) {
    showProfile();
  }
  if (event.target.closest("#feed-filter")) {
    if (!currentUser) {
      showLogin();
      return;
    }
    activeView = activeView === "following" ? "home" : "following";
    renderNav();
    updateViewTitle();
    void refreshBackendData();
  }
  if (event.target.closest("#add-story")) showStoryComposer();
  if (event.target.closest("#clear-search")) {
    document.getElementById("search-input").value = "";
    renderPosts();
  }
});

