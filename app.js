function showLogin(signup = false, reset = false) {
  const formMode = reset ? "reset" : signup ? "signup" : "login";
  const title = reset ? t("resetTitle") : signup ? t("signupTitle") : t("loginTitle");
  const description = reset ? t("resetCopy") : signup ? t("signupCopy") : t("loginCopy");
  const emailField = authField(t("email"), "email", "email", "email", "guest@example.com", 'required maxlength="254"');
  const passwordFields = signup
    ? `${authField(t("username"), "handle", "text", "username", "guest", 'required minlength="3" maxlength="32" pattern="[A-Za-z0-9._-]{3,32}"')}<small class="field-hint">${t("usernameHint")}</small> ${authPasswordField(t("password"), "password", "new-password", t("passwordHint"), 'required minlength="8" maxlength="72"', true)} ${authPasswordField(t("confirmPassword"), "confirmPassword", "new-password", "••••••••", 'required minlength="8" maxlength="72"')}`
    : reset ? "" : authField(t("password"), "password", "password", "current-password", "••••••••", 'required maxlength="72"');
  const submitText = reset ? t("sendReset") : signup ? t("createAccount") : t("continue");
  const note = window.wallBackend?.configured ? t("authBackendWarning") : t("authConfigMissing");
  const form = `<form class="form-stack" id="auth-form" data-mode="${formMode}" novalidate>${signup ? authField(t("fullName"), "name", "text", "name", "Guest", 'required maxlength="48"') : ""}${emailField}${passwordFields}<span class="form-error hidden" id="auth-form-error" role="alert"></span><button class="button button-dark" type="submit">${submitText} ${icon("arrow")}</button></form>`;
  openModal(`<div class="auth-panel"><span class="modal-kicker">${icon("sparkle")} THE WALL</span><h2 class="modal-title">${title}</h2><p class="modal-copy">${description}</p>${form}<div class="${window.wallBackend?.configured ? "demo-warning" : "connection-warning"}">${icon(window.wallBackend?.configured ? "check" : "settings")}<span>${note}</span></div>
    ${!signup && !reset ? `<button class="modal-switch" id="reset-auth">${t("resetPassword")}</button>` : ""}
    ${!reset ? `<button class="modal-switch" id="switch-auth">${signup ? t("haveAccount") : t("noAccount")} <strong>${signup ? t("logInLink") : t("createAccount")}</strong></button>` : `<button class="modal-switch" id="switch-auth"><strong>${t("logInLink")}</strong></button>`}</div>`, "auth");
  const formElement = document.getElementById("auth-form");
  const fieldNames = ["email", "password", "confirmPassword", "handle"];
  formElement.querySelector("[data-password-toggle]")?.addEventListener("click", (event) => {
    const button = event.currentTarget;
    const input = formElement.elements.namedItem("password");
    const isVisible = input.type === "text";
    input.type = isVisible ? "password" : "text";
    button.innerHTML = icon(isVisible ? "eye" : "eye-off");
    button.setAttribute("aria-label", t(isVisible ? "showPassword" : "hidePassword"));
    button.setAttribute("aria-pressed", String(!isVisible));
  });
  formElement.addEventListener("input", (event) => {
    const input = event.target;
    if (!(input instanceof HTMLInputElement)) return;
    if (input.name === "email" && input.value && !input.validity.valid) setAuthError(formElement, "email", t("invalidEmail"));
    else if (input.name === "handle" && input.value && !USERNAME_PATTERN.test(input.value)) setAuthError(formElement, "handle", t("invalidUsername"));
    else setAuthError(formElement, input.name, "");
    if (input.name === "password" || input.name === "confirmPassword") {
      const password = formElement.elements.namedItem("password")?.value;
      const confirmPassword = formElement.elements.namedItem("confirmPassword")?.value;
      if (confirmPassword && password !== confirmPassword) setAuthError(formElement, "confirmPassword", t("passwordMismatch"));
      else setAuthError(formElement, "confirmPassword", "");
    }
  });
  document.getElementById("switch-auth")?.addEventListener("click", () => showLogin(!signup && !reset, false));
  document.getElementById("reset-auth")?.addEventListener("click", () => showLogin(false, true));
  formElement.addEventListener("submit", async (event) => {
    event.preventDefault();
    const data = new FormData(formElement);
    const email = String(data.get("email") || "").trim();
    const password = String(data.get("password") || "");
    let valid = true;
    if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      setAuthError(formElement, "email", t("invalidEmail"));
      valid = false;
    }
    if (signup && password.length < 8) {
      setAuthError(formElement, "password", t("shortPassword"));
      valid = false;
    }
    const username = String(data.get("handle") || "");
    if (signup && !USERNAME_PATTERN.test(username)) {
      setAuthError(formElement, "handle", t("invalidUsername"));
      valid = false;
    }
    if (signup && password !== String(data.get("confirmPassword") || "")) {
      setAuthError(formElement, "confirmPassword", t("passwordMismatch"));
      valid = false;
    }
    if (!valid) return;
    if (!window.wallBackend?.configured) {
      formElement.querySelector("#auth-form-error").textContent = t("authConfigMissing");
      formElement.querySelector("#auth-form-error").classList.remove("hidden");
      return;
    }
    const submit = formElement.querySelector('[type="submit"]');
    submit.disabled = true;
    try {
      if (reset) {
        await window.wallBackend.sendPasswordReset(email);
        showToast(t("resetSent"));
        closeModal();
        return;
      }
      if (signup) {
        const name = String(data.get("name") || "").trim();
        const handle = String(data.get("handle") || "").trim().toLowerCase();
        await window.wallBackend.signUp({ email, password, name, handle });
        closeModal();
        showToast(t("checkEmail"));
        return;
      }
      await window.wallBackend.signIn({ email, password });
      closeModal();
      showToast(t("loginSuccess"));
    } catch (error) {
      const mapped = mapAuthError(error, signup);
      setAuthError(formElement, mapped.field, mapped.message);
      if (!formElement.querySelector(`[data-error-for="${mapped.field}"]`)) {
        const formError = formElement.querySelector("#auth-form-error");
        formError.textContent = mapped.message;
        formError.classList.remove("hidden");
      }
    } finally {
      submit.disabled = false;
    }
  });
  for (const field of fieldNames) {
    const input = formElement.elements.namedItem(field);
    if (input) input.autocomplete = field === "password" ? (signup ? "new-password" : "current-password") : input.autocomplete;
  }
}

